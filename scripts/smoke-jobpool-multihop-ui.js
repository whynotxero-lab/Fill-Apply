'use strict';
const fs = require('fs');
const { createSuite } = require('./test-harness');
const suite = createSuite('smoke-jobpool-multihop-ui');
const runner = fs.readFileSync('runner/runner.js', 'utf8');
suite.ok(runner.indexOf('MAX_HANDOFF_HOPS') !== -1, 'multi-hop hop cap present');
suite.ok(runner.indexOf('needsHandoffHop') !== -1, 'needsHandoffHop helper present');
suite.ok(runner.indexOf('Following redirect hop') !== -1, 'hop progress message');
const types = fs.readFileSync('lib/types.js', 'utf8');
suite.ok(types.indexOf('zahid-jobpool.vercel.app') !== -1, 'JobPool default URL in types');
const panel = fs.readFileSync('ui/panel-app.js', 'utf8');
suite.ok(panel.indexOf('FILL_APPLY_LOAD_JOBPOOL') !== -1, 'panel loads JobPool');
suite.ok(panel.indexOf('btnOpenJobPool') !== -1, 'Open JobPool button wired');
const popup = fs.readFileSync('popup/popup.html', 'utf8');
suite.ok(popup.indexOf('btnOpenJobPool') !== -1, 'popup has Open JobPool');
suite.ok(popup.indexOf('btnSeed') === -1 || popup.indexOf('Open JobPool') !== -1, 'popup Seed replaced');
const side = fs.readFileSync('sidepanel/sidepanel.html', 'utf8');
suite.ok(side.indexOf('btnLoadJobPool') !== -1, 'sidepanel Load from JobPool');
const sw = fs.readFileSync('background/service-worker.js', 'utf8');
suite.ok(sw.indexOf('FILL_APPLY_LOAD_JOBPOOL') !== -1, 'SW handler present');
suite.finish();
